// Writes skills/open-artifacts/constructor/themes/palettes.json: the CSS of every colour theme,
// so the standalone constructor can bake `--theme` into a local file without depending on this
// workspace package. Run `pnpm --filter @open-artifacts/shared gen:palettes` after editing
// src/artifact-themes.ts; __tests__/artifact-themes.test.ts fails if the file is stale.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ARTIFACT_THEME_IDS, buildThemeCss, listArtifactThemes } from "../dist/artifact-themes.js";
import { ARTIFACT_FONT_IDS, buildFontCss, listArtifactFonts } from "../dist/artifact-fonts.js";

const out = fileURLToPath(new URL("../../../skills/open-artifacts/constructor/themes/palettes.json", import.meta.url));
const palettes = Object.fromEntries(ARTIFACT_THEME_IDS.map((id) => [id, buildThemeCss(id)]));
writeFileSync(out, JSON.stringify(palettes, null, 2) + "\n");
console.log(`wrote ${out}`);

// Same idea for fonts: { id: { imports, rules } }, so `--font` can be baked into a local file.
const fontsOut = fileURLToPath(new URL("../../../skills/open-artifacts/constructor/themes/fonts.json", import.meta.url));
writeFileSync(fontsOut, JSON.stringify(Object.fromEntries(ARTIFACT_FONT_IDS.map((id) => [id, buildFontCss(id)])), null, 2) + "\n");
console.log(`wrote ${fontsOut}`);

// The web app declares its types by hand (see apps/web/src/lib/api.ts), so it gets the picker data
// as a generated module instead of importing the workspace package.
const webOut = fileURLToPath(new URL("../../../apps/web/src/lib/artifactThemes.generated.ts", import.meta.url));
writeFileSync(webOut, webModule());
console.log(`wrote ${webOut}`);

export function webModule() {
  return (
    `// GENERATED by packages/shared/scripts/gen-artifact-themes.mjs from src/artifact-themes.ts — do not edit.\n` +
    `export type ArtifactThemeId = ${ARTIFACT_THEME_IDS.map((i) => JSON.stringify(i)).join(" | ")};\n\n` +
    `export interface ArtifactThemeSummary {\n  id: ArtifactThemeId;\n  name: string;\n  description: string;\n  fontFamily: string;\n  fontsUrl?: string;\n` +
    `  light: Record<"bg" | "surface" | "fg" | "accent" | "c1" | "c2" | "c3" | "c4", string>;\n  dark: Record<"bg" | "surface" | "fg" | "accent" | "c1" | "c2" | "c3" | "c4", string>;\n}\n\n` +
    `export const ARTIFACT_THEMES: ArtifactThemeSummary[] = ${JSON.stringify(listArtifactThemes(), null, 2)};\n\n` +
    `export type ArtifactFontId = ${ARTIFACT_FONT_IDS.map((i) => JSON.stringify(i)).join(" | ")};\n\n` +
    `export interface ArtifactFontSummary {\n  id: ArtifactFontId;\n  name: string;\n  style: "sans" | "serif" | "mono";\n}\n\n` +
    `export const ARTIFACT_FONTS: ArtifactFontSummary[] = ${JSON.stringify(listArtifactFonts().map(({ id, name, style }) => ({ id, name, style })), null, 2)};\n`
  );
}
